import fs from "node:fs";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
const read=(file)=>fs.readFileSync(new URL("../"+file,import.meta.url),"utf8");
const html=read("hamjamiyat.html"),js=read("hamjamiyat.js"),css=read("hamjamiyat.css"),worker=read("service-worker.js"),home=read("index.html"),admin=read("admin.html"),vercel=JSON.parse(read("vercel.json"));
const ids=[...html.matchAll(/id="([^"]+)"/g)].map(x=>x[1]);
assert.equal(ids.length,new Set(ids).size,"Duplicate community page IDs");
for(const id of ["hpAuthGate","hpAuthForm","hpGoogleLogin","hpAppShell","hpDrawer","hpTabFeed","hpTabDirectory","hpTabProfile","hpTabActivity","hpTabSettings","hpCvCurrent","hpCopyProfileLink","hpActivityChart","hpPrivacyForm"])assert.ok(ids.includes(id),"Missing UI control: "+id);
assert.ok(html.includes('data-auth-mode="register"'));
assert.ok(js.includes("signUp(")&&js.includes("signInWithPassword")&&js.includes('signInWithOAuth({provider:"google"'));
for(const table of ["member_profiles","member_posts","member_post_likes","member_post_comments","member_portfolio_items","member_activity_events"])assert.ok(js.includes('from("'+table+'")'),"Missing data source: "+table);
assert.ok(js.includes("record_member_daily_visit")&&js.includes('timeZone:"Asia/Tashkent"')&&js.includes(".range(offset,offset+size-1)"));
assert.ok(js.includes("createSignedUrl(p.cv_object_path,300)")&&!js.includes('$("hpCvPublic").checked'));
assert.ok(js.includes("data.visibility!==\"members\"")&&js.includes("show_in_directory"));
assert.ok(js.includes("safeStorage.get("));
assert.ok(worker.includes('"/hamjamiyat.css"')&&worker.includes('"/hamjamiyat.js"'));
assert.ok(worker.includes('const PRIVATE_PATHS = new Set(["/admin.html", "/kabinet.html", "/hamjamiyat.html"])'));
const precache=worker.match(/const PRECACHE_URLS = \[([\s\S]*?)\];/)?.[1]||"";
assert.ok(!precache.includes('"/hamjamiyat.html"'));
assert.ok(home.includes('hamjamiyat.html?mode=login#hpAuthGate'));
assert.ok(home.includes('hamjamiyat.html?mode=register#hpAuthCard'));
assert.ok(admin.includes("admin_google_console_check"));
assert.equal(vercel.headers.find(x=>x.source==="/hamjamiyat.html").headers.find(x=>x.key==="Cache-Control").value,"private, no-store, max-age=0, must-revalidate");
assert.ok(css.includes("@media(max-width:600px)"));
execFileSync(process.execPath,["--check","hamjamiyat.js"]);
console.log("✓ Auth, member profiles, feed, portfolio, private CV, activity graphs and cache/privacy checks");
